"""Authenticate and bound HTTP input before FastAPI parses any patient document."""
from __future__ import annotations

import asyncio
import logging
import secrets

from starlette.responses import JSONResponse

from .config import Settings

logger = logging.getLogger(__name__)


class LocalBoundary:
    def __init__(self, app, settings: Settings):
        self.app = app
        self.token = settings.api_token.encode("ascii")
        self.max_bytes = settings.max_bytes + 1024 * 1024  # Multipart envelope allowance.
        self.slots = asyncio.Semaphore(4)
        self.body_timeout = 30

    async def __call__(self, scope, receive, send):
        if scope["type"] != "http":
            return await self.app(scope, receive, send)

        started = finished = False

        async def private_send(message):
            nonlocal started, finished
            if message["type"] == "http.response.start":
                started = True
                headers = [(k, v) for k, v in message.get("headers", [])
                           if k.lower() not in {b"cache-control", b"x-content-type-options"}]
                message = {**message, "headers": headers + [
                    (b"cache-control", b"no-store"), (b"x-content-type-options", b"nosniff"),
                ]}
            elif message["type"] == "http.response.body" and not message.get("more_body", False):
                finished = True
            await send(message)

        async def reject(status, detail):
            headers = {"WWW-Authenticate": "Bearer"} if status == 401 else None
            await JSONResponse({"detail": detail}, status_code=status, headers=headers)(scope, receive, private_send)

        headers = {}
        for key, value in scope.get("headers", []):
            key = key.lower()
            if key in headers and key in {b"host", b"authorization", b"content-length", b"transfer-encoding"}:
                return await reject(400, "Duplicate security-relevant header.")
            headers[key] = value
        host = headers.get(b"host", b"").split(b":", 1)[0].lower()
        if host not in {b"127.0.0.1", b"localhost", b"testserver"}:
            return await reject(400, "Loopback host required.")
        if b"origin" in headers:
            return await reject(403, "Browser-origin requests disabled.")
        auth = headers.get(b"authorization", b"").split(b" ", 1)
        if len(auth) != 2 or auth[0].lower() != b"bearer" or not secrets.compare_digest(auth[1], self.token):
            return await reject(401, "Valid bearer token required.")
        length = headers.get(b"content-length")
        if length is not None:
            if not length or any(c < 48 or c > 57 for c in length) or b"transfer-encoding" in headers:
                return await reject(400, "Invalid Content-Length.")
            if len(length) > 12 or int(length) > self.max_bytes:
                return await reject(413, "Request too large.")

        async with self.slots:
            body = bytearray()

            async def read_body():
                while True:
                    message = await receive()
                    if message["type"] == "http.disconnect":
                        return False
                    chunk = message.get("body", b"")
                    if len(body) + len(chunk) > self.max_bytes:
                        raise OverflowError
                    body.extend(chunk)
                    if not message.get("more_body", False):
                        return True

            try:
                connected = await asyncio.wait_for(read_body(), timeout=self.body_timeout)
            except OverflowError:
                return await reject(413, "Request too large.")
            except TimeoutError:
                return await reject(408, "Request body timed out.")
            if not connected:
                return
            if length is not None and len(body) != int(length):
                return await reject(400, "Content-Length does not match request body.")
            delivered = False

            async def replay():
                nonlocal delivered
                if not delivered:
                    delivered = True
                    return {"type": "http.request", "body": bytes(body), "more_body": False}
                return await receive()

            try:
                await self.app(scope, replay, private_send)
            except Exception as error:
                # Third-party exceptions may contain document text or tokens. Do
                # not let the server print their message, traceback or local values.
                logger.error("Request processing failed (%s).", type(error).__name__)
                if not started:
                    await reject(500, "Operation failed. No report was generated by this request.")
                elif not finished:
                    await private_send({"type": "http.response.body", "body": b"", "more_body": False})
